"""Generate TS structural types from the published OpenAPI. No network/dependencies.

Deliberately fail on unsupported constructs instead of silently emitting `any`.
The source document is generated by tools/export_openapi.py, never from UI guesses.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "frontend/src/api/schema.d.ts"

def ts(schema):
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return f'schemas[{json.dumps(schema["$ref"].split("/")[-1])}]'
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(x, ensure_ascii=False) for x in schema["enum"])
    for keyword, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if keyword in schema:
            return "(" + separator.join(ts(x) for x in schema[keyword]) + ")"
    kind = schema.get("type")
    if kind in ("integer", "number"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return kind
    if kind == "array":
        return f'Array<{ts(schema.get("items", {}))}>'
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = [f'{json.dumps(k, ensure_ascii=False)}{"" if k in required else "?"}: {ts(v)};'
                  for k, v in schema.get("properties", {}).items()]
        extra = schema.get("additionalProperties", True)
        if extra:
            fields.append(f'[key: string]: {ts(extra) if isinstance(extra, dict) else "unknown"};')
        return "{ " + " ".join(fields) + " }"
    raise ValueError(f"Unsupported schema: {schema!r}")

def generate():
    spec = json.loads((ROOT / "docs/api/openapi.json").read_text(encoding="utf-8"))
    lines = ["// GENERATED by tools/generate_frontend_types.py. DO NOT EDIT.",
             "// Source: docs/api/openapi.json. Extra properties remain unknown, never any.",
             "export interface schemas {"]
    for name, schema in spec["components"]["schemas"].items():
        lines.append(f'  {json.dumps(name)}: {ts(schema)};')
    return "\n".join(lines + ["}", ""])

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = generate()
    if args.check:
        if not DEST.exists() or DEST.read_text(encoding="utf-8") != data:
            sys.exit("Frontend types are stale. Run python tools/generate_frontend_types.py")
        print("Frontend API types are current")
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(data, encoding="utf-8")
        print(f"Wrote {DEST.relative_to(ROOT)}")
